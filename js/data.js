/* The row as an object: { region, pop, urban 0..1, zone, freedom, type, st: {six levels}, economy, authority, openness, res: [4] }. */
function rowOf(iso) {
  if (cache[iso]) return cache[iso];
  const raw = ROWS[iso], regionId = raw ? REGION_ID[raw[0]] : null;
  const region = regionId || "asia";
  const r = raw ? raw.slice(1) : REGION_ROW[region];
  const o = { iso, region, curated: !!raw, pop: +r[0] || 0, urban: (+r[1] || 60) / 100, zone: r[2], freedom: r[3], type: r[4],
              st: { infra: r[5], military: r[7], academia: r[8], medical: r[9], stability: r[10], technology: r[11] },
              economy: r[6], authority: r[12], openness: r[13], res: [r[14], r[15], r[16], r[17]] };
  cache[iso] = o;
  return o;
}
